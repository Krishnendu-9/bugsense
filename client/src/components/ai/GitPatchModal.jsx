import { useState } from 'react';
import { GitPullRequest, Copy, Check, FileCode, Info, RefreshCw } from 'lucide-react';
import toast from 'react-hot-toast';
import Modal from '../common/Modal.jsx';
import { formatDate } from '../../utils/helpers.js';

const copyToClipboard = async (text, successMessage) => {
  try {
    await navigator.clipboard.writeText(text);
    toast.success(successMessage);
    return true;
  } catch {
    toast.error('Clipboard access was blocked by the browser');
    return false;
  }
};

const lineStyle = (line) => {
  if (line.startsWith('+') && !line.startsWith('+++')) return 'text-status-resolved bg-status-resolved/10 block px-1 -mx-1 rounded-sm';
  if (line.startsWith('-') && !line.startsWith('---')) return 'text-danger bg-danger/10 block px-1 -mx-1 rounded-sm';
  if (line.startsWith('@@')) return 'text-secondary font-semibold block pt-1';
  if (line.startsWith('---') || line.startsWith('+++')) return 'text-muted font-semibold';
  return 'text-muted';
};

/**
 * Shows a model-generated patch, or why there is none. A patch saved on the
 * bug is shown as-is; `onRegenerate` asks the model for a new one.
 */
export default function GitPatchModal({ patch, onClose, onRegenerate, regenerating = false }) {
  const [copied, setCopied] = useState(false);

  if (!patch) return null;

  const hasDiff = Boolean(patch.diff);

  const handleCopy = async () => {
    if (await copyToClipboard(patch.diff, 'Unified Git diff copied to clipboard')) {
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }
  };

  const subtitle = hasDiff
    ? `Generated by Claude${patch.generatedAt ? ` on ${formatDate(patch.generatedAt, 'MMM d, h:mm a')}` : ''} — review before applying`
    : 'No patch available';

  return (
    <Modal
      title="AI Unified Git Patch"
      subtitle={subtitle}
      icon={GitPullRequest}
      onClose={onClose}
      size="xl"
      footer={
        <>
          {hasDiff ? (
            <span className="text-xs text-muted">
              Apply via: <code className="text-text-base bg-track px-1.5 py-0.5 rounded">git apply patch.diff</code>
            </span>
          ) : (
            <span />
          )}
          <div className="flex gap-2">
            {onRegenerate && (
              <button
                onClick={onRegenerate}
                disabled={regenerating}
                className="btn-secondary text-xs px-3 py-1.5 flex items-center gap-1.5 disabled:opacity-60"
              >
                <RefreshCw size={13} className={regenerating ? 'animate-pulse' : ''} />
                {regenerating ? 'Regenerating...' : 'Regenerate'}
              </button>
            )}
            {hasDiff && (
              <button onClick={handleCopy} className="btn-primary text-xs px-4 py-1.5 flex items-center gap-1.5">
                {copied ? <Check size={14} /> : <Copy size={14} />} Copy Git Patch
              </button>
            )}
            <button onClick={onClose} className="btn-secondary text-xs px-3 py-1.5">
              Close
            </button>
          </div>
        </>
      }
    >
      {regenerating ? (
        <div className="space-y-3" aria-busy="true" aria-label="Generating patch">
          <div className="skeleton h-14 w-full rounded-xl" />
          <div className="skeleton h-64 w-full rounded-xl" />
        </div>
      ) : !hasDiff ? (
        <div className="flex items-start gap-3 rounded-xl p-4 bg-track border border-border text-sm text-muted">
          <Info size={16} className="flex-shrink-0 mt-0.5 text-primary" />
          <p>{patch.explanation || 'The AI service did not return a patch for this incident.'}</p>
        </div>
      ) : (
        <div className="space-y-4">
          {patch.explanation && (
            <div className="bg-primary/10 border border-primary/20 rounded-xl p-3.5 text-xs text-text-base leading-relaxed">
              <span className="font-semibold text-primary block mb-1">Fix Rationale:</span>
              {patch.explanation}
            </div>
          )}

          <div className="rounded-xl border border-border overflow-hidden bg-canvas">
            <div className="flex items-center justify-between px-4 py-2 bg-track border-b border-hairline text-xs text-muted">
              <span className="flex items-center gap-1.5">
                <FileCode size={13} /> unified diff (git apply)
              </span>
              <button
                onClick={handleCopy}
                className="flex items-center gap-1 text-[11px] font-semibold text-primary hover:text-primary-hover transition-colors"
              >
                {copied ? <Check size={12} /> : <Copy size={12} />}
                {copied ? 'Copied' : 'Copy Diff'}
              </button>
            </div>

            <div className="p-4 font-mono text-xs overflow-x-auto max-h-96 leading-5">
              {patch.diff.split('\n').map((line, i) => (
                <div key={i} className={`${lineStyle(line)} whitespace-pre`}>
                  {line || ' '}
                </div>
              ))}
            </div>
          </div>
        </div>
      )}
    </Modal>
  );
}
